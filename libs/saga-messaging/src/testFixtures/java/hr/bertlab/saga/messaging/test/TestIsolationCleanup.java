package hr.bertlab.saga.messaging.test;

import java.util.List;
import org.springframework.amqp.core.AmqpAdmin;
import org.springframework.amqp.core.Declarables;
import org.springframework.amqp.core.Exchange;
import org.springframework.amqp.core.Queue;
import org.springframework.beans.factory.DisposableBean;
import org.springframework.jdbc.core.simple.JdbcClient;

/**
 * Drops the schema and broker objects of one isolated test run when its context closes. Being a
 * {@link DisposableBean}, it runs after listener containers and schedulers have stopped, and before the
 * DataSource and AmqpAdmin it uses are destroyed. Contexts whose names were not generated by
 * {@link SagaTestSupport} are left alone.
 */
public class TestIsolationCleanup implements DisposableBean {

    private final JdbcClient jdbc;
    private final AmqpAdmin admin;
    private final List<Declarables> declarables;
    private final String schema;
    private final String prefix;

    public TestIsolationCleanup(
            JdbcClient jdbc, AmqpAdmin admin, List<Declarables> declarables, String schema, String prefix) {
        this.jdbc = jdbc;
        this.admin = admin;
        this.declarables = declarables;
        this.schema = schema;
        this.prefix = prefix;
    }

    @Override
    public void destroy() {
        if (SagaTestSupport.TEST_SCHEMA.matcher(schema).matches()) {
            jdbc.sql("DROP SCHEMA IF EXISTS \"" + schema + "\" CASCADE").update();
        }
        if (!SagaTestSupport.TEST_BROKER_NAME.matcher(prefix).matches()) {
            return;
        }
        for (Declarables group : declarables) {
            group.getDeclarablesByType(Queue.class).stream()
                    .map(Queue::getName)
                    .filter(name -> name.startsWith(prefix))
                    .forEach(admin::deleteQueue);
            group.getDeclarablesByType(Exchange.class).stream()
                    .map(Exchange::getName)
                    .filter(name -> name.startsWith(prefix))
                    .forEach(admin::deleteExchange);
        }
    }
}
